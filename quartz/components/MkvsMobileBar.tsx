// Раскладка элементов управления по режиму экрана: верхняя панель телефона и
// кнопка оглавления там, где для колонки оглавления нет места.
//
// Компонент сам ничего не рисует. Всё нужное на странице уже есть, но лежит в
// трёх разных местах разметки: «гамбургер» Проводника и поиск — в левой
// колонке, переключатель темы — в панели над текстом, оглавление — в правой
// колонке. Скрипт переносит узлы туда, где они помещаются в текущем режиме
// (custom.scss, п.6):
//
//   compact   — тема и оглавление уезжают в левую колонку: она становится
//               закреплённой верхней панелью, и все четыре кнопки оказываются
//               обычными элементами одной flex-строки. Порядок и отступы тогда
//               задаются стилями, а не подгонкой координат у трёх независимо
//               закреплённых кнопок;
//   columns-2 — колонки оглавления нет (правую Quartz показывает только шире
//               1200px), поэтому оглавление уезжает кнопкой в панель над
//               текстом. Иначе оно просто пропало бы со страницы;
//   columns-3 — все узлы стоят там, где их отрисовала раскладка.
//
// Почему переносом узлов, а не стилями: кнопки должны стоять в одной строке и
// в одном порядке, а в разметке они лежат в трёх разных контейнерах. Три
// независимо позиционированные кнопки пришлось бы держать вровень руками.
//
// Закрепление панели и вид кнопок — в custom.scss, п.8.1 (кнопка оглавления)
// и п.12 (панель).
